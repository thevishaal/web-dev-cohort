/**
 * Create a class `MathHelper` with a static method `square(n)` that returns n * n. Call MathHelper.square(4) and log the result.
 */

// solution

// Create MathHelper class with static method
class MathHelper {
  static square(n) {
    return n * n;
  }
}
// Call static method and log
console.log(MathHelper.square(4));
